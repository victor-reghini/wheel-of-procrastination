export class I18nManager {
  constructor(defaultLang = 'pt') {
    this.currentLang = defaultLang;
    this.supportedLanguages = ['pt', 'en', 'es', 'it', 'fr'];
  }

  init(savedLang) {
    if (savedLang && this.supportedLanguages.includes(savedLang)) {
      this.currentLang = savedLang;
    } else {
      // Detecção de idioma do navegador
      const browserLang = (navigator.language || navigator.userLanguage || 'pt').slice(0, 2).toLowerCase();
      this.currentLang = this.supportedLanguages.includes(browserLang) ? browserLang : 'pt';
    }
    return this.currentLang;
  }

  setLanguage(lang) {
    if (this.supportedLanguages.includes(lang)) {
      this.currentLang = lang;
      return true;
    }
    return false;
  }

  t(key, params = {}) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS['pt'];
    let text = dict[key] !== undefined ? dict[key] : (TRANSLATIONS['pt'][key] || key);

    if (typeof text === 'string') {
      Object.keys(params).forEach(p => {
        text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
      });
    }
    return text;
  }

  getDefaultTasks() {
    return DEFAULT_TASKS_BY_LANG[this.currentLang] || DEFAULT_TASKS_BY_LANG['pt'];
  }
}

